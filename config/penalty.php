<?php
/**
 * ペナルティ点システムの設定（Admin限定機能）
 *
 * 会員の「入金期限の遅れ」を検知してペナルティ点を加算する。
 * 初期値は 0 点で、遅れるほど点数が増える（多いほど悪い）。
 *
 * points_per_day : 「入金期限を過ぎても未入金」の集金1件につき、遅延1日あたりに加算する点数。
 *                  対象種別ごとに変えられる（合宿/遠征/物販）。
 *                  例: 2 なら 3日遅れ = 6点。複数件あれば各件の遅延日数を合計して ×point。
 * grace_days     : 期限の翌日からではなく、何日の猶予を置いてから加点するか（0で期限翌日から）。
 *
 * 集計方針:
 *   - 未入金の集金は元データから「期限〜今日」の遅延日数を動的に計算する。
 *   - 入金が確認された時点で、その時の遅延日数を確定し snapshot に記録する（永続化）。
 *     これにより、入金後や元データ削除後も過去の遅延ペナルティが維持される。
 *   - 手動調整分（member_penalty_adjustments）は別管理で影響を受けない。
 */

return [
    // 遅延1日あたりの加算点（対象種別ごと）
    'points_per_day' => [
        'camp'        => 2,   // 合宿費
        'expedition'  => 2,   // 遠征費
        'merchandise' => 2,   // 物販の振込
    ],

    // 期限超過とみなすまでの猶予日数（期限日 + grace_days を過ぎたら加点）
    'grace_days' => 0,
];
